"""Generate the HTTP envelope types from the actual app OpenAPI, without inputs."""
from __future__ import annotations

import argparse
from pathlib import Path

DEST = Path(__file__).resolve().parents[1] / "frontend/src/api/generated.ts"


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        import json
        return json.dumps(schema["const"])
    if 'enum' in schema:
        import json
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    return {"string": "string", "integer": "number", "number": "number",
            "boolean": "boolean", "null": "null", "object": "Record<string, unknown>"}.get(kind, "unknown")


def generate():
    from workflow_doctor.api.app import create_app
    schema = create_app().openapi()
    # Fail loudly on upload/route changes rather than generating a fictional client.
    paths = schema["paths"]
    upload = paths["/api/v1/scans"]["post"]["requestBody"]["content"]["multipart/form-data"]["schema"]
    body = (schema["components"]["schemas"][upload["$ref"].rsplit("/", 1)[1]]
            if "$ref" in upload else upload)
    assert body["properties"]["files"]["type"] == "array"
    assert "get" in paths["/api/v1/scans/{scan_id}/report"]
    lines = ["// Generated by python -m tools.export_frontend_contract; do not edit."]
    for name in ("ErrorDetail", "ErrorResponse", "DiagnosticRecord", "DiagnosticStatistics", "DiagnosticSummary", "ScanResponse"):
        model = schema["components"]["schemas"][name]
        lines.append(f"export interface {name} {{")
        for field, value in model["properties"].items():
            optional = "" if field in model.get("required", []) else "?"
            lines.append(f"  {field}{optional}: {ts_type(value)}")
        lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not DEST.exists() or DEST.read_text(encoding="utf-8") != content:
            print("Frontend contract differs from actual OpenAPI")
            return 1
        print("Frontend HTTP envelope matches actual OpenAPI")
    else:
        DEST.parent.mkdir(parents=True, exist_ok=True)
        DEST.write_text(content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
